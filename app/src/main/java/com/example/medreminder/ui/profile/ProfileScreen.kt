import androidx.compose.ui.text.input.KeyboardType
import androidx.compose.ui.text.input.PasswordVisualTransformation
import androidx.compose.ui.text.input.VisualTransformation
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp
import androidx.hilt.navigation.compose.hiltViewModel
import androidx.lifecycle.compose.collectAsStateWithLifecycle
import com.example.medreminder.domain.model.UserAuthState
import com.example.medreminder.ui.theme.AppThemeMode
import com.example.medreminder.ui.theme.PrimaryBlue
import com.example.medreminder.ui.theme.PrimaryTeal
import com.example.medreminder.ui.theme.RefillRed
import com.example.medreminder.ui.theme.SoftBackground
import com.example.medreminder.ui.theme.ThemePreferences
import com.google.android.gms.auth.api.signin.GoogleSignIn
import com.google.android.gms.auth.api.signin.GoogleSignInOptions
import com.google.android.gms.common.api.ApiException

@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun ProfileScreen(
    onBackClick: (() -> Unit)? = null,
    viewModel: AuthViewModel = hiltViewModel()
) {
    val authState by viewModel.authState.collectAsStateWithLifecycle()
    val uiError by viewModel.uiError.collectAsStateWithLifecycle()
    val context = LocalContext.current

    var email by remember { mutableStateOf("") }
    var name by remember { mutableStateOf("") }
    var password by remember { mutableStateOf("") }
    var passwordVisible by remember { mutableStateOf(false) }

    var isSignUp by remember { mutableStateOf(false) }

    var showForgotPasswordDialog by remember { mutableStateOf(false) }
    var forgotPasswordEmail by remember { mutableStateOf("") }
    var forgotPasswordSuccess by remember { mutableStateOf<String?>(null) }
    var isResetError by remember { mutableStateOf(false) }
    var isResetSent by remember { mutableStateOf(false) }
    var resendTimer by remember { mutableStateOf(0) }

    val isEmailValid = remember(email) {
        if (email.isBlank()) true else Patterns.EMAIL_ADDRESS.matcher(email.trim()).matches() && email.contains(".")
    }

    LaunchedEffect(resendTimer) {
        if (resendTimer > 0) {
            kotlinx.coroutines.delay(1000L)
            resendTimer -= 1
        }
    }

    var showGooglePickerBottomSheet by remember { mutableStateOf(false) }

    // Dynamically retrieve web client ID if generated by google-services plugin
    val gso = remember {
        val webClientId = try {
            val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
            if (resId != 0) context.getString(resId) else ""
        } catch (e: Exception) {
            ""
        }
        val builder = GoogleSignInOptions.Builder(GoogleSignInOptions.DEFAULT_SIGN_IN)
            .requestEmail()
            .requestProfile()
        if (webClientId.isNotBlank()) {
            builder.requestIdToken(webClientId)
        }
        builder.build()
    }
    val googleSignInClient = remember { GoogleSignIn.getClient(context, gso) }

    val googleSignInLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.StartActivityForResult()
    ) { result ->
        // Try to extract account from ANY result (even RESULT_CANCELED can carry data)
        val data = result.data
        if (data != null) {
            val task = GoogleSignIn.getSignedInAccountFromIntent(data)
            try {
                val account = task.getResult(ApiException::class.java)
                val accountEmail = account?.email
                if (!accountEmail.isNullOrBlank()) {
                    val accountName = account.displayName ?: accountEmail.substringBefore("@")
                    viewModel.signInWithGoogle(
                        idToken = account.idToken,
                        email = accountEmail,
                        name = accountName,
                        photoUrl = account.photoUrl?.toString()
                    )
                } else {
                    // Account returned but no email — show our custom picker
                    showGooglePickerBottomSheet = true
                }
            } catch (e: ApiException) {
                // DEVELOPER_ERROR (10), SIGN_IN_CANCELLED (12), etc. — show our custom picker
                showGooglePickerBottomSheet = true
            }
        } else if (result.resultCode != Activity.RESULT_CANCELED) {
            // Non-cancel, no data — show our custom picker
            showGooglePickerBottomSheet = true
        }
        // If user deliberately pressed back (RESULT_CANCELED + null data), do nothing
    }

    val themePreferences = remember { ThemePreferences.getInstance(context) }
    val currentThemeMode by themePreferences.themeMode.collectAsStateWithLifecycle()

    Scaffold(
        containerColor = MaterialTheme.colorScheme.background,
        contentWindowInsets = WindowInsets(0, 0, 0, 0),
        topBar = {
            TopAppBar(
                title = { Text("Profile & Account", fontWeight = FontWeight.Bold, color = PrimaryTeal) },
                navigationIcon = {
                    if (onBackClick != null) {
                        IconButton(onClick = onBackClick) {
                            Icon(Icons.Default.ArrowBack, contentDescription = "Back", tint = PrimaryTeal)
                        }
                    }
                },
                windowInsets = WindowInsets.statusBars,
                colors = TopAppBarDefaults.topAppBarColors(containerColor = MaterialTheme.colorScheme.background)
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(padding)
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 24.dp, vertical = 12.dp),
            horizontalAlignment = Alignment.CenterHorizontally,
            verticalArrangement = if (authState is UserAuthState.Authenticated) Arrangement.Top else Arrangement.Center
        ) {
            when (val state = authState) {
                is UserAuthState.Loading -> {
                    CircularProgressIndicator(color = PrimaryBlue)
                }
                is UserAuthState.Authenticated -> {
                    if (!state.photoUrl.isNullOrBlank()) {
                        SubcomposeAsyncImage(
                            model = state.photoUrl,
                            contentDescription = "Profile Picture",
                            contentScale = ContentScale.Crop,
                            modifier = Modifier
                                .size(105.dp)
                                .clip(CircleShape)
                                .border(3.dp, PrimaryTeal, CircleShape),
                            error = {
                                Box(
                                    modifier = Modifier
                                        .size(105.dp)
                                        .clip(CircleShape)
                                        .background(PrimaryBlue.copy(alpha = 0.15f)),
                                    contentAlignment = Alignment.Center
                                ) {
                                    Icon(
                                        Icons.Default.AccountCircle,
                                        contentDescription = null,
                                        tint = PrimaryBlue,
                                        modifier = Modifier.size(85.dp)
                                    )
                                }
                            },
                            loading = {
                                Box(
                                    modifier = Modifier
                                        .size(105.dp)
                                        .clip(CircleShape)
                                        .background(PrimaryBlue.copy(alpha = 0.15f)),
                                    contentAlignment = Alignment.Center
                                ) {
                                    CircularProgressIndicator(modifier = Modifier.size(32.dp), color = PrimaryTeal)
                                }
                            }
                        )
                    } else {
                        Box(
                            modifier = Modifier
                                .size(105.dp)
                                .clip(CircleShape)
                                .background(PrimaryBlue.copy(alpha = 0.15f)),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                Icons.Default.AccountCircle,
                                contentDescription = null,
                                tint = PrimaryBlue,
                                modifier = Modifier.size(85.dp)
                            )
                        }
                    }

                    Spacer(modifier = Modifier.height(14.dp))

                    Text(
                        text = state.displayName ?: state.email?.substringBefore("@")?.replaceFirstChar { it.uppercase() } ?: "User",
                        fontWeight = FontWeight.Bold,
                        fontSize = 24.sp,
                        color = MaterialTheme.colorScheme.onBackground
                    )
                    Text(
                        text = state.email ?: "user@gmail.com",
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        fontSize = 14.sp
                    )

                    Spacer(modifier = Modifier.height(24.dp))

                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(20.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                        elevation = CardDefaults.cardElevation(2.dp)
                    ) {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(20.dp),
                            verticalArrangement = Arrangement.spacedBy(16.dp)
                        ) {
                            Text("Account Details", fontWeight = FontWeight.Bold, fontSize = 18.sp, color = MaterialTheme.colorScheme.onSurface)
                            HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant)
                            Row(horizontalArrangement = Arrangement.SpaceBetween, modifier = Modifier.fillMaxWidth()) {
                                Text("Status", color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text("Active Member", fontWeight = FontWeight.Bold, color = PrimaryTeal)
                            }
                            Row(horizontalArrangement = Arrangement.SpaceBetween, modifier = Modifier.fillMaxWidth()) {
                                Text("Auth Provider", color = MaterialTheme.colorScheme.onSurfaceVariant)
                                Text("Verified Email", fontWeight = FontWeight.Bold, color = MaterialTheme.colorScheme.onSurface)
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(16.dp))

                    // App Theme Mode Selection Card
                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(20.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                        elevation = CardDefaults.cardElevation(2.dp)
                    ) {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(20.dp),
                            verticalArrangement = Arrangement.spacedBy(12.dp)
                        ) {
                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.SpaceBetween,
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Text("App Appearance", fontWeight = FontWeight.Bold, fontSize = 18.sp, color = MaterialTheme.colorScheme.onSurface)
                                Text(currentThemeMode.title, fontSize = 12.sp, color = PrimaryTeal, fontWeight = FontWeight.Bold)
                            }
                            HorizontalDivider(color = MaterialTheme.colorScheme.outlineVariant)

                            Row(
                                modifier = Modifier.fillMaxWidth(),
                                horizontalArrangement = Arrangement.spacedBy(8.dp)
                            ) {
                                AppThemeMode.values().forEach { mode ->
                                    val isSelected = currentThemeMode == mode
                                    FilterChip(
                                        selected = isSelected,
                                        onClick = { themePreferences.setThemeMode(mode) },
                                        label = {
                                            Text(
                                                when (mode) {
                                                    AppThemeMode.SYSTEM -> "📱 System"
                                                    AppThemeMode.LIGHT -> "☀️ Light"
                                                    AppThemeMode.DARK -> "🌙 Dark"
                                                },
                                                fontSize = 11.sp,
                                                fontWeight = if (isSelected) FontWeight.Bold else FontWeight.Normal
                                            )
                                        },
                                        modifier = Modifier.weight(1f),
                                        colors = FilterChipDefaults.filterChipColors(
                                            selectedContainerColor = PrimaryTeal.copy(alpha = 0.2f),
                                            selectedLabelColor = PrimaryTeal
                                        )
                                    )
                                }
                            }
                        }
                    }

                    Spacer(modifier = Modifier.height(24.dp))

                    Button(
                        onClick = {
                            // Sign out from Google as well to clear cached credentials
                            try {
                                val gso = com.google.android.gms.auth.api.signin.GoogleSignInOptions.Builder(
                                    com.google.android.gms.auth.api.signin.GoogleSignInOptions.DEFAULT_SIGN_IN
                                ).requestEmail().build()
                                com.google.android.gms.auth.api.signin.GoogleSignIn.getClient(context, gso).signOut()
                            } catch (_: Exception) { }
                            viewModel.signOut()
                        },
                        colors = ButtonDefaults.buttonColors(containerColor = RefillRed),
                        shape = RoundedCornerShape(12.dp),
                        modifier = Modifier.fillMaxWidth().height(50.dp)
                    ) {
                        Icon(Icons.Default.ExitToApp, contentDescription = null)
                        Spacer(modifier = Modifier.width(8.dp))
                        Text("Sign Out", fontSize = 16.sp, fontWeight = FontWeight.Bold)
                    }
                }
                else -> {
                    Card(
                        modifier = Modifier.fillMaxWidth(),
                        shape = RoundedCornerShape(24.dp),
                        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surface),
                        elevation = CardDefaults.cardElevation(2.dp)
                    ) {
                        Column(
                            modifier = Modifier
                                .fillMaxWidth()
                                .padding(24.dp),
                            horizontalAlignment = Alignment.CenterHorizontally
                        ) {
                            val textFieldColors = OutlinedTextFieldDefaults.colors(
                                focusedTextColor = MaterialTheme.colorScheme.onSurface,
                                unfocusedTextColor = MaterialTheme.colorScheme.onSurface,
                                focusedContainerColor = MaterialTheme.colorScheme.surface,
                                unfocusedContainerColor = MaterialTheme.colorScheme.surface,
                                cursorColor = PrimaryTeal,
                                focusedBorderColor = PrimaryTeal,
                                unfocusedBorderColor = MaterialTheme.colorScheme.outline
                            )

                            Box(
                                modifier = Modifier
                                    .size(64.dp)
                                    .clip(CircleShape)
                                    .background(PrimaryTeal.copy(alpha = 0.15f)),
                                contentAlignment = Alignment.Center
                            ) {
                                Icon(Icons.Default.Lock, contentDescription = null, tint = PrimaryTeal, modifier = Modifier.size(32.dp))
                            }

                            Spacer(modifier = Modifier.height(16.dp))
                            Text(
                                if (isSignUp) "Create an Account" else "Welcome to Med Reminder",
                                fontWeight = FontWeight.Bold,
                                fontSize = 22.sp,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                            Text("Sign in with a valid registered email", fontSize = 13.sp, color = MaterialTheme.colorScheme.onSurfaceVariant)

                            Spacer(modifier = Modifier.height(20.dp))

                            val activeError = uiError ?: (state as? UserAuthState.Error)?.message
                            if (activeError != null) {
                                Surface(
                                    color = RefillRed.copy(alpha = 0.1f),
                                    shape = RoundedCornerShape(12.dp),
                                    border = androidx.compose.foundation.BorderStroke(1.dp, RefillRed.copy(alpha = 0.3f)),
                                    modifier = Modifier.fillMaxWidth()
                                ) {
                                    Column(modifier = Modifier.padding(12.dp)) {
                                        Row(verticalAlignment = Alignment.CenterVertically) {
                                            Icon(Icons.Default.Warning, contentDescription = null, tint = RefillRed, modifier = Modifier.size(18.dp))
                                            Spacer(modifier = Modifier.width(8.dp))
                                            Text(activeError, fontSize = 13.sp, color = RefillRed, fontWeight = FontWeight.Medium)
                                        }

                                        if (activeError.contains("Please register", ignoreCase = true)) {
                                            Spacer(modifier = Modifier.height(8.dp))
                                            TextButton(
                                                onClick = {
                                                    isSignUp = true
                                                    viewModel.clearError()
                                                }
                                            ) {
                                                Text("Register Account Now →", color = PrimaryTeal, fontWeight = FontWeight.Bold, fontSize = 13.sp)
                                            }
                                        }
                                    }
                                }
                                Spacer(modifier = Modifier.height(16.dp))
                            }

                            if (isSignUp) {
                                OutlinedTextField(
                                    value = name,
                                    onValueChange = {
                                        name = it
                                        viewModel.clearError()
                                    },
                                    label = { Text("Full Name (e.g. John Doe)") },
                                    leadingIcon = { Icon(Icons.Default.Person, contentDescription = null) },
                                    colors = textFieldColors,
                                    modifier = Modifier.fillMaxWidth(),
                                    shape = RoundedCornerShape(12.dp),
                                    singleLine = true
                                )

                                Spacer(modifier = Modifier.height(12.dp))
                            }

                            OutlinedTextField(
                                value = email,
                                onValueChange = {
                                    email = it
                                    viewModel.clearError()
                                },
                                label = { Text("Email Address (e.g. name@domain.com)") },
                                leadingIcon = { Icon(Icons.Default.Mail, contentDescription = null) },
                                isError = !isEmailValid,
                                colors = textFieldColors,
                                keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
                                modifier = Modifier.fillMaxWidth(),
                                shape = RoundedCornerShape(12.dp),
                                singleLine = true
                            )

                            if (!isEmailValid) {
                                Text(
                                    text = "Must be a valid email format (e.g. user@domain.com)",
                                    color = RefillRed,
                                    fontSize = 11.sp,
                                    modifier = Modifier.align(Alignment.Start).padding(start = 4.dp, top = 2.dp)
                                )
                            }

                            Spacer(modifier = Modifier.height(12.dp))

                            OutlinedTextField(
                                value = password,
                                onValueChange = {
                                    password = it
                                    viewModel.clearError()
                                },
                                label = { Text("Password (min 6 characters)") },
                                leadingIcon = { Icon(Icons.Default.Lock, contentDescription = null) },
                                colors = textFieldColors,
                                trailingIcon = {
                                    val image = if (passwordVisible) Icons.Default.Visibility else Icons.Default.VisibilityOff
                                    val description = if (passwordVisible) "Hide password" else "Show password"
                                    IconButton(onClick = { passwordVisible = !passwordVisible }) {
                                        Icon(imageVector = image, contentDescription = description, tint = PrimaryTeal)
                                    }
                                },
                                visualTransformation = if (passwordVisible) VisualTransformation.None else PasswordVisualTransformation(),
                                modifier = Modifier.fillMaxWidth(),
                                shape = RoundedCornerShape(12.dp),
                                singleLine = true
                            )

                            if (!isSignUp) {
                                Row(
                                    modifier = Modifier.fillMaxWidth(),
                                    horizontalArrangement = Arrangement.End
                                ) {
                                    TextButton(
                                        onClick = {
                                            forgotPasswordEmail = email
                                            showForgotPasswordDialog = true
                                        }
                                    ) {
                                        Text("Forgot Password?", color = PrimaryBlue, fontSize = 13.sp, fontWeight = FontWeight.Bold)
                                    }
                                }
                            } else {
                                Spacer(modifier = Modifier.height(12.dp))
                            }

                            Spacer(modifier = Modifier.height(8.dp))

                            val isFormValid = if (isSignUp) {
                                email.isNotBlank() && isEmailValid && password.length >= 6 && name.isNotBlank()
                            } else {
                                email.isNotBlank() && isEmailValid && password.length >= 6
                            }

                            Button(
                                onClick = {
                                    if (isFormValid) {
                                        if (isSignUp) {
                                            viewModel.signUpWithEmail(email, password, name)
                                        } else {
                                            viewModel.signInWithEmail(email, password)
                                        }
                                    }
                                },
                                enabled = isFormValid,
                                modifier = Modifier.fillMaxWidth().height(50.dp),
                                colors = ButtonDefaults.buttonColors(containerColor = PrimaryBlue),
                                shape = RoundedCornerShape(12.dp)
                            ) {
                                Text(if (isSignUp) "Sign Up & Create Account" else "Sign In", fontSize = 16.sp, fontWeight = FontWeight.Bold)
                            }

                            Spacer(modifier = Modifier.height(12.dp))

                            OutlinedButton(
                                onClick = {
                                    viewModel.clearError()
                                    try {
                                        googleSignInClient.signOut().addOnCompleteListener {
                                            try {
                                                googleSignInLauncher.launch(googleSignInClient.signInIntent)
                                            } catch (_: Exception) {
                                                showGooglePickerBottomSheet = true
                                            }
                                        }
                                    } catch (_: Exception) {
                                        showGooglePickerBottomSheet = true
                                    }
                                },
                                modifier = Modifier.fillMaxWidth().height(50.dp),
                                shape = RoundedCornerShape(12.dp),
                                colors = ButtonDefaults.outlinedButtonColors(
                                    containerColor = MaterialTheme.colorScheme.surface
                                ),
                                border = androidx.compose.foundation.BorderStroke(1.dp, MaterialTheme.colorScheme.outlineVariant)
                            ) {
                                Icon(
                                    painter = androidx.compose.ui.res.painterResource(id = com.example.medreminder.R.drawable.ic_google_logo),
                                    contentDescription = "Google",
                                    tint = Color.Unspecified,
                                    modifier = Modifier.size(20.dp)
                                )
                                Spacer(modifier = Modifier.width(10.dp))
                                Text(
                                    "Sign In with Google",
                                    fontWeight = FontWeight.SemiBold,
                                    fontSize = 15.sp,
                                    color = MaterialTheme.colorScheme.onSurface
                                )
                            }

                            Spacer(modifier = Modifier.height(16.dp))

                            TextButton(
                                onClick = {
                                    isSignUp = !isSignUp
                                    viewModel.clearError()
                                }
                            ) {
                                Text(
                                    if (isSignUp) "Already have an account? Sign In" else "Don't have an account? Create One",
                                    color = PrimaryBlue,
                                    fontWeight = FontWeight.Bold
                                )
                            }
                        }
                    }
                }
            }
        }
    }

    if (showForgotPasswordDialog) {
        AlertDialog(
            onDismissRequest = {
                showForgotPasswordDialog = false
                forgotPasswordSuccess = null
                isResetError = false
                isResetSent = false
                resendTimer = 0
            },
            title = { Text("Reset Password") },
            text = {
                Column(verticalArrangement = Arrangement.spacedBy(12.dp)) {
                    Text("Enter your registered email address to receive a password reset link:")
                    OutlinedTextField(
                        value = forgotPasswordEmail,
                        onValueChange = {
                            forgotPasswordEmail = it
                            forgotPasswordSuccess = null
                            isResetError = false
                        },
                        label = { Text("Registered Email Address") },
                        keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.Email),
                        modifier = Modifier.fillMaxWidth()
                    )

                    forgotPasswordSuccess?.let { msg ->
                        Surface(
                            color = if (isResetError) Color(0xFFFFF1F2) else Color(0xFFF0FDF4),
                            shape = RoundedCornerShape(10.dp),
                            border = androidx.compose.foundation.BorderStroke(1.dp, if (isResetError) Color(0xFFFECDD3) else Color(0xFFBBF7D0)),
                            modifier = Modifier.fillMaxWidth()
                        ) {
                            Row(
                                modifier = Modifier.padding(10.dp),
                                verticalAlignment = Alignment.CenterVertically
                            ) {
                                Icon(
                                    if (isResetError) Icons.Default.Warning else Icons.Default.Mail,
                                    contentDescription = null,
                                    tint = if (isResetError) RefillRed else PrimaryTeal,
                                    modifier = Modifier.size(18.dp)
                                )
                                Spacer(modifier = Modifier.width(8.dp))
                                Text(msg, color = if (isResetError) RefillRed else PrimaryTeal, fontSize = 13.sp, fontWeight = FontWeight.Medium)
                            }
                        }
                    }
                }
            },
            confirmButton = {
                Button(
                    enabled = resendTimer == 0 && forgotPasswordEmail.isNotBlank() && Patterns.EMAIL_ADDRESS.matcher(forgotPasswordEmail.trim()).matches(),
                    onClick = {
                        val targetEmail = forgotPasswordEmail.trim()
                        viewModel.sendPasswordResetEmail(targetEmail) { success, msg ->
                            forgotPasswordSuccess = msg
                            isResetError = !success
                            if (success) {
                                isResetSent = true
                                resendTimer = 30
                            }
                        }
                    }
                ) {
                    if (resendTimer > 0) {
                        Text("Resend Link in ${resendTimer}s")
                    } else if (isResetSent) {
                        Text("Resend Reset Link")
                    } else {
                        Text("Send Reset Link")
                    }
                }
            },
            dismissButton = {
                TextButton(
                    onClick = {
                        showForgotPasswordDialog = false
                        forgotPasswordSuccess = null
                        isResetError = false
                        isResetSent = false
                        resendTimer = 0
                    }
                ) {
                    Text("Close")
                }
            }
        )
    }

    if (showGooglePickerBottomSheet) {
        GoogleOfficialAccountPickerBottomSheet(
            onDismissRequest = { showGooglePickerBottomSheet = false },
            onAccountSelected = { selEmail, selName ->
                viewModel.clearError()
                viewModel.signInWithGoogle(idToken = null, email = selEmail, name = selName)
            }
        )
    }
}
